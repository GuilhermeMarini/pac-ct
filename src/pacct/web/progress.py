# Runtime do cliente
# -----------------------------------------------------------------------------

# A bar fixed to the top of the viewport, deliberately outside the document
# flow: the tools have different layouts, and this way none of them had to
# make room for it.
#
# The two phases split the bar: the upload occupies 0-60%, the server-side
# processing 60-100%. On a large RDB the two take comparable time, so mapping
# the upload onto 0-100% would falsely read as "finished" with half the work
# still to do.
# Absolute, and it resolves under every mount: `mount.py` answers `/static/...`
# at the root AND behind any prefix -- the same reason `library/client.py`
# points at an absolute path for `SelLibrary`.
PROGRESS_JS_URL = "/static/js/lib/progress.js"

PROGRESS_TAG = f'<script src="{PROGRESS_JS_URL}"></script>\n'


def inject_progress_runtime(html: str) -> str:
    """Insert the bar's tag just before `</body>`, or at the end.

    **The position is the contract, and it did not move in B17b.** The tag goes
    exactly where the 219-line inline block used to go: immediately before
    `</body>`, which is AFTER the page's own `<script src>`. That ordering is
    what lets every tool leave `SelProgress` alone at the top level of its
    script -- and it is why the tag carries no `defer` and no `async`, either
    of which would let the page's own script run first and find it missing.

    It is a `<script src>` rather than the runtime itself since B17b: the
    JavaScript is `frontend/src/lib/progress.ts`, built to
    `web/static/js/lib/progress.js`. What that buys is that the file is linted,
    type-checked and diffable, which 219 lines inside a Python string never
    were. What it costs is one more request per HTML response, uncached
    (`mount.py` serves `.js` as `no-store`), and that price is stated here
    rather than discovered later.
    """
    idx = html.rfind("</body>")
    if idx == -1:
        return html + PROGRESS_TAG
    return html[:idx] + PROGRESS_TAG + html[idx:]
